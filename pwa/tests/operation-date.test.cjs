test("manual edits preserve historical document dates but stamp new reversal events",()=>{
 const now=Date.now(),old=now-86400000,manualValue="2026-11-15T10:00",at=parseOperationDate(manualValue);
 const reversed=stampOperationRecord({store:"invoices",record:{date:old,status:"REVERSED",reversedAt:now},mode:"MANUAL",manualValue,now});
 assert.equal(reversed.date,old);assert.equal(reversed.reversedAt,at);
 const cleared=stampOperationRecord({store:"checks",record:{date:old,status:"CLEARED",statusChangedAt:now,createdAt:old},mode:"MANUAL",manualValue,now});
 assert.equal(cleared.date,old);assert.equal(cleared.createdAt,old);assert.equal(cleared.statusChangedAt,at);
});
test("automatic mode supplies a date when a transaction record has no date yet",()=>{
 const x=stampOperationRecord({store:"imports",record:{supplierId:1},mode:"AUTO",now:456});
 assert.equal(x.date,456);
});

test("manual date stamps the reversal event without rewriting the original foreign payment date",()=>{
 const now=Date.now(),old=now-86400000,manualValue="2026-11-15T11:15",at=parseOperationDate(manualValue);
 const payment=stampOperationRecord({store:"foreignPayablePayments",record:{date:old,status:"REVERSED",reversedAt:now},mode:"MANUAL",manualValue,now});
 assert.equal(payment.date,old);assert.equal(payment.reversedAt,at);
});

test("manual operation dates are enabled for sales orders and stamp their creation/update events",()=>{
 const now=Date.now(),manualValue="2026-11-16T08:20",at=parseOperationDate(manualValue);
 assert.equal(OPERATION_DATE_STORES.has("salesOrders"),true);
 const order=stampOperationRecord({store:"salesOrders",record:{date:now,createdAt:now,updatedAt:now,validUntil:now+86400000},mode:"MANUAL",manualValue,now});
 assert.equal(order.date,at);assert.equal(order.createdAt,at);assert.equal(order.updatedAt,at);assert.equal(order.validUntil,now+86400000);
});
